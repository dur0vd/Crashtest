// Independent measured rest positions, not generated by the path follower.
const source = 'Условный обмер для независимой проверки правил (не валидация)';
function fixture(context: StopContext | undefined = { reason: 'other-voluntary', intentional: true, durationBeforeStart: 600 }, options: Partial<Actor> = {}) {
  const scene = emptyScene();
  scene.env = { accidentDate: '2026-10-21T12:00', federalCity: 'other', duration: 8, surface: 'dry' };
  scene.roads = [{ id: 'road', pts: [{ x: -200, y: 0 }, { x: 200, y: 0 }], lanes: 1, center: 'dashed', zone: 'city', oneWay: false, smooth: false }];
  const actor: Actor = { id: 'car', kind: 'vehicle', type: 'car', x: 0, y: 2.5, heading: 0, speed: 0, delay: 0,
    color: '#aaa', path: [], flags: { drunk: false, noLicense: false, flees: false }, stopContext: context, ...options };
  scene.actors = [actor];
  return scene;
}
function measured(scene: Scene): Timeline {
  const n = Math.round(scene.env.duration / DT) + 1;
  const tracks = new Map(scene.actors.map(a => [a.id, { id: a.id, x: new Float32Array(n).fill(a.x), y: new Float32Array(n).fill(a.y), h: new Float32Array(n).fill(a.heading), v: new Float32Array(n), present: new Uint8Array(n).fill(1), free: new Uint8Array(n), waypointTimes: [] } as Track]));
  return { dt: DT, duration: scene.env.duration, mu: 0.7, n, tracks, collisions: [] };
}
function run(scene: Scene, tl = measured(scene)) {
  const ctx: Ctx = { ...prepare(scene, tl), findings: [], priorityGraphs: [], events: [], onc: new Map(), lightViolations: new Map(), stopSkipped: new Map(), pedEntry: new Map() };
  checkStopping(ctx, f => ctx.findings.push({ causal: false, ...f }));
  return ctx;
}
function results(scene: Scene, tl = measured(scene)) { return analyze(scene, tl); }
const violated = (ctx: Ctx, ref: string) => ctx.findings.filter(f => f.severity === 'violation' && f.refs.includes(ref));
const basis = (ctx: Ctx, name: string) => ctx.findings.filter(f => f.trace?.stoppingBasis === name);
const sign = (kind: string, options: Partial<Sign> = {}): Sign => ({ id: 'sign', kind, x: -30, y: 5, angle: 0, ...options });
const place = (kind: StopPlace['kind'], boundary = [{ x: -10, y: -5 }, { x: 10, y: -5 }, { x: 10, y: 5 }, { x: -10, y: 5 }]): StopPlace => ({ id: 'place', kind, boundary, source });
const refs = (scene: Scene) => results(scene).findings.flatMap(f => f.refs.filter(r => r.startsWith('koap:12.19') || r.startsWith('koap:12.16')));
function noParkingExemptions(scene: Scene) {
  Object.assign(scene.actors[0].stopContext!, { disabilityExemptionEligible: false, disabilityBadge: false, postalLiveryEligible: false, taxiMeterOn: false });
  scene.actors[0].routeContext = { taxi: false, regularService: false };
}

