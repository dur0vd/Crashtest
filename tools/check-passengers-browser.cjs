const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async()=>{
const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const results=[];
let currentPage;
process.on('unhandledRejection',async e=>{if(currentPage) await currentPage.screenshot({path:'/tmp/passengers-error.png'});console.error(e);process.exit(1)});
for (const viewport of [{width:1440,height:1000},{width:390,height:844}]) {
 const page=await browser.newPage({viewport}); currentPage=page; page.setDefaultTimeout(6000); console.log('START',viewport.width); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.CRASHTEST_URL || 'http://localhost:5173/');
 await page.getByRole('button',{name:'Примеры',exact:true}).click();
 await page.getByRole('button',{name:'Ребёнок 6 лет: один ремень вместо ДУУ',exact:false}).click();
 await page.waitForTimeout(200);
 let box=await page.locator('canvas').boundingBox(); const scale=Math.max(1.2,Math.min(30,box.width/120,box.height/30));
 await page.mouse.click(box.x+box.width/2-45*scale,box.y+box.height/2);
 if (viewport.width < 600 && !(await page.locator('body').evaluate(e=>e.classList.contains('sheet')))) await page.locator('#btnSheet').click();
 console.log('open-summary', viewport.width); await page.getByText('Пассажиры и защита',{exact:true}).click();
 let form=page.getByTestId('passengers-form');
 const selectField = label => form.locator('label.field').filter({has: page.getByText(label,{exact:true})}).locator('select');
 await form.getByText('Возраст, полных лет',{exact:true}).scrollIntoViewIfNeeded();
 assert.equal(await form.getByLabel('Возраст, полных лет',{exact:true}).inputValue(),'6');
 assert.equal(await selectField('ДУУ используется').inputValue(),'no');
 await form.getByLabel('Возраст, полных лет',{exact:true}).fill('7');
 await form.getByLabel('Возраст, полных лет',{exact:true}).dispatchEvent('change');
 await form.getByLabel('Возраст, полных лет',{exact:true}).fill('6');
 await form.getByLabel('Возраст, полных лет',{exact:true}).dispatchEvent('change');
 await selectField('ДУУ используется').selectOption('yes');
 await selectField('ДУУ соответствует весу и росту').selectOption('yes');
 await selectField('ДУУ и ребёнок размещены по руководству').selectOption('yes');
 await form.getByRole('button',{name:'Добавить пассажира',exact:true}).click();
 if (viewport.width < 600 && !(await page.locator('body').evaluate(e=>e.classList.contains('sheet')))) await page.locator('#btnSheet').click();
 console.log('open-summary', viewport.width); await page.getByText('Пассажиры и защита',{exact:true}).click();
 form=page.getByTestId('passengers-form'); assert.equal(await form.locator('[data-passenger-id]').count(),2);
 await form.locator('[data-passenger-id]').last().getByRole('button',{name:'Удалить пассажира',exact:true}).click();
 if (viewport.width < 600 && !(await page.locator('body').evaluate(e=>e.classList.contains('sheet')))) await page.locator('#btnSheet').click();
 console.log('open-summary', viewport.width); await page.getByText('Пассажиры и защита',{exact:true}).click();
 form=page.getByTestId('passengers-form'); assert.equal(await form.locator('[data-passenger-id]').count(),1);
 await form.getByLabel('Рост, см (для этапа 09)',{exact:true}).fill('115');
 await form.getByLabel('Рост, см (для этапа 09)',{exact:true}).dispatchEvent('change');
 await form.getByLabel('Возраст, полных лет',{exact:true}).scrollIntoViewIfNeeded();
 await page.screenshot({path:`/tmp/passengers-${viewport.width}.png`});
 await page.waitForTimeout(500);
 const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('crashtest.scene.v1')));
 assert.equal(stored.actors[0].passengers[0].heightCm,115);
 assert.equal(stored.actors[0].passengers[0].restraintInstalledCorrectly,true);
 if(viewport.width < 600) await page.locator('#sheetClose').click();
 await page.locator('#btnPlay').click();
 if(viewport.width < 600) await page.locator('#btnSheet').click();
 await page.getByRole('tab',{name:/Разбор/}).click();
 await page.waitForTimeout(300);
 const report=await page.locator('#pane-report').innerText();
 assert(!report.includes('ч. 3 ст. 12.23')); assert(report.includes('ДУУ'));
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 results.push({viewport,passed:['preset loaded','age boundary editing','tri-state protection fields','add/remove passenger','height + restraint persisted','correct report without 12.23(3)','no page errors','no document horizontal overflow']});
 console.log('PASS',viewport.width); await page.close();
}
console.log(JSON.stringify(results,null,2)); await browser.close();
})();
